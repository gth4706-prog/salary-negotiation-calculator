//  중간 명도 흙빛 배경은 밝은 글자도 어두운 글자도 대비가 안 나온다.
//  실제로 계산해 보면 배경 L*45 위에서는 흰 글자 5.2:1 / 검은 글자 3.2:1 —
//  어두운 잉크 쪽은 본문 AA(4.5:1)를 물리적으로 못 넘는다.
