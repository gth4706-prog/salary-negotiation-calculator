/**
 * 냉기 지대 — **여기 있으면 가만히 있어도 커진다.**
 *
 * 쿨링포그(바닥분수)다. 한국 여름 길거리에 실제로 있고, 있으면 사람이 모인다.
 * 그늘과 달리 **움직이지 않는다.** 그래서 지도에서 값이 고정된 자리가 되고,
 * 해가 돌면서 어느 냉기가 그늘에 들어오는지가 바뀐다 — 그게 이 게임의 시계다.
 *
 * **자리 수가 사람 수보다 적어야 한다.** 처음엔 7개를 뒀더니 봇 6마리가 하나씩 차지하고
 * 눌러앉아, 10분에 교전이 2번뿐이고 냉기 체류가 94.5% 였다. 다툴 이유가 없으면
 * '쟁탈전'이 아니라 '주차장'이 된다. 4개로 줄였다.
 *
 * ⚠ **건물(block) 위에 놓으면 안 된다.** 건물은 자기 몸이 늘 그늘이라, 거기에 냉기를 겹치면
 * 해가 어디 있든 '안 녹으면서 커지는' 영구 명당이 된다. 그 자리를 잡은 사람은 아무 판단도
 * 할 필요가 없어진다. (처음에 실수로 정자 위에 놓았고 테스트가 잡았다.)
 * 파라솔 그림자는 해를 따라 움직이므로 냉기와 겹쳐도 **한때**일 뿐이다 — 그게 노림수다.
 */
const COLD = [
  { x: 1500, y: 1500, r: 210 },   // 한복판 — 가장 좋은 자리이자 가장 위험한 자리
  { x: 700,  y: 1150, r: 150 },
  { x: 2250, y: 1150, r: 150 },
  { x: 1150, y: 2200, r: 150 }
];

export const ARENA = {
  w: C.WORLD,
  h: C.WORLD,
  ground: GROUND,
  lines: LINES,
  obstacles: OBSTACLES,
  cold: COLD
};

/** 이 점이 냉기 지대 안인가 */
export function coldAt(x, y) {
  for (const c of COLD) {
    const dx = x - c.x, dy = y - c.y;
    if (dx * dx + dy * dy <= c.r * c.r) return true;
  }
  return false;
}

