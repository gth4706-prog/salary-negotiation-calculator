  //  ctx: { nick, unitKey, floor, boss, heroKey, heroHpFrac, selfHpFrac }
  //  반환: 완성된 문장 또는 null(쿨다운·확률 탈락).
  pick: function (ctx) {
    var now = Date.now();
    if (now - this._lastAt < this.COOLDOWN) return null;
    if (Math.random() > this.CHANCE) return null;

    //  후보 풀 조립 — 상황 풀이 있으면 일반 풀과 반반쯤 되게 눌러 담는다.
    //  (일반이 96개라 그냥 합치면 상황 대사가 묻힌다 — 상황이 재미의 본체다.)
    var pools = [];
    function addAll(arr, times) {
      if (!arr || !arr.length) return;
      for (var t = 0; t < (times || 1); t++) for (var i = 0; i < arr.length; i++) pools.push(arr[i]);
    }
    var uArr = ctx.unitKey && this.BY_UNIT[ctx.unitKey];
    var hArr = ctx.heroKey && this.BY_HERO[ctx.heroKey];
    if (ctx.heroHpFrac !== undefined && ctx.heroHpFrac < 0.30) addAll(this.HERO_LOW, 10);
    else if (ctx.selfHpFrac !== undefined && ctx.selfHpFrac < 0.35) addAll(this.SELF_LOW, 8);
    if (ctx.boss) addAll(this.BOSS_FLOOR, 8);
    else if (ctx.floor >= 30) addAll(this.HIGH_FLOOR, 6);
    else if (ctx.floor >= 1 && ctx.floor <= 3) addAll(this.EARLY, 8);
    addAll(uArr, 8);
    addAll(hArr, 5);
    addAll(this.GENERIC, 1);
    if (!pools.length) return null;

    //  같은 판에서 같은 대사 반복 금지 — 최근 24개를 피해서 몇 번 다시 굴린다.
    var line = null;
    for (var tries = 0; tries < 8; tries++) {
      var cand = pools[Math.floor(Math.random() * pools.length)];
      if (this._recent.indexOf(cand) < 0) { line = cand; break; }
    }
    if (!line) line = pools[Math.floor(Math.random() * pools.length)];
    this._recent.push(line);
    if (this._recent.length > 24) this._recent.shift();
    this._lastAt = now;

    var nick = ctx.nick || '침입자';
    //  {라} — '{n}{라}고?' 처럼 서술격 조사(받침이면 '이라', 아니면 '라').
    var out = line.replace(/\{라\}/g, (function () {
      var c = nick.length ? nick.charCodeAt(nick.length - 1) : 0;
      var has = (c >= 0xAC00 && c <= 0xD7A3) && ((c - 0xAC00) % 28) > 0;
      return has ? '이라' : '라';
    })());
    //  {의}/{도} 는 받침 무관이라 그대로 치환만 한다.
    out = out.replace(/\{의\}/g, '의').replace(/\{도\}/g, '도');
    return GAME.UI && GAME.UI.fillName ? GAME.UI.fillName(out, nick)
                                       : out.replace(/\{n\}/g, nick);
  }
